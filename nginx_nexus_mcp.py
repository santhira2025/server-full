from mcp.server.fastmcp import FastMCP
from pydantic import BaseModel, Field, ConfigDict
from typing import Optional, List, Dict, Any, Literal
from enum import Enum
import json, os, subprocess, tempfile

mcp = FastMCP("nginx_nexus_mcp")

class ResponseFormat(str, Enum):
    MARKDOWN = "markdown"
    JSON = "json"

def _safe_json(data): return json.dumps(data, indent=2, default=str)
def _run_cmd(cmd): return subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=10)
def _handle_error(e): return f"Error: {type(e).__name__} — {str(e)}"

NGINX_CONF_DIR = os.environ.get("NGINX_CONF_DIR", "/etc/nginx")

# ---- INPUT MODELS ----

class NginxConfigGenInput(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")
    server_name: str = Field(..., description="Domain name (e.g., 'api.santhira.com')")
    upstream_servers: List[str] = Field(..., description="Backend servers (e.g., ['10.0.1.1:8000', '10.0.1.2:8000'])")
    listen_port: int = Field(default=443, ge=80, le=65535)
    ssl: bool = Field(default=True, description="Enable HTTPS")
    ssl_cert_path: Optional[str] = Field(default=None, description="SSL certificate path")
    ssl_key_path: Optional[str] = Field(default=None, description="SSL key path")
    load_balance: Literal["round_robin", "least_conn", "ip_hash", "random"] = Field(default="round_robin")
    rate_limit: Optional[str] = Field(default=None, description="Rate limit (e.g., '100r/s', '10r/m')")
    cache_enabled: bool = Field(default=False, description="Enable proxy caching")
    websocket: bool = Field(default=False, description="Enable WebSocket support")
    health_check_path: Optional[str] = Field(default=None, description="Backend health check path (e.g., '/health')")
    max_body_size: str = Field(default="10m", description="Client max body size")
    custom_headers: Optional[Dict[str, str]] = Field(default=None)
    gzip: bool = Field(default=True, description="Enable gzip compression")

class NginxTestInput(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")
    config_content: Optional[str] = Field(default=None, description="Config content to test (or test existing)")

class NginxStatusInput(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")
    response_format: ResponseFormat = Field(default=ResponseFormat.MARKDOWN)

class NginxSSLInput(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")
    domain: str = Field(..., description="Domain for SSL certificate")
    action: Literal["generate_self_signed", "certbot_command", "check_expiry"] = Field(...)

class NginxSecurityInput(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")
    server_name: str = Field(..., description="Domain to generate security headers for")
    level: Literal["basic", "strict", "paranoid"] = Field(default="strict")

class NginxUpstreamAdvisorInput(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")
    use_case: str = Field(..., description="Describe your application and traffic pattern")
    backend_count: int = Field(default=3, ge=1, le=100)
    expected_rps: Optional[int] = Field(default=None, description="Expected requests per second")
    response_format: ResponseFormat = Field(default=ResponseFormat.MARKDOWN)

class NginxHealthInput(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")
    response_format: ResponseFormat = Field(default=ResponseFormat.MARKDOWN)

